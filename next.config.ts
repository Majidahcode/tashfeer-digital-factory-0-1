import type { NextConfig } from "next";

/**
 * Hostnames of a tunnel the dev server may be opened through (comma-separated), e.g.
 *   TUNNEL_HOSTS=abc-def.trycloudflare.com npm run dev
 * `next dev` refuses its dev-only endpoints to any origin but localhost — among them the HMR WebSocket, and without
 * that connection the page is never hydrated: no moving background, no lit tiles, no phrases (reproduced 2026-10-23:
 * the dev server logged "Blocked cross-origin request to Next.js dev resource /_next/hmr", and the page from that
 * origin stayed static; with the origin listed it hydrated). An entry may use `*` for one label (`*.trycloudflare.com`
 * for any quick tunnel). None by default: the dev server stays closed to other origins unless asked. `next start`
 * (the production build) has no such check, and is the better way to show a public preview.
 */
export function tunnelHosts(value = process.env.TUNNEL_HOSTS): string[] {
  return (value ?? "")
    .split(",")
    .map((h) => h.trim())
    .filter(Boolean);
}

const hosts = tunnelHosts();

/**
 * STATIC_EXPORT=1 next build — a static copy of the site in out/ (every page here is static), for a private
 * interactive preview where no Node server runs. Images are then served as they are, without the optimizer.
 */
const staticExport = process.env.STATIC_EXPORT === "1";

const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  images: {
    // Approved artwork is served from /public/assets (generated by scripts/sync-assets.mjs).
    formats: ["image/avif", "image/webp"],
    ...(staticExport ? { unoptimized: true } : {}),
  },
  // the chunks under /p/_next: the preview host reserves top-level names starting with "_" (the build's out/_next is
  // moved to out/p/_next after the export — scripts/export-preview.sh)
  ...(staticExport ? { output: "export" as const, trailingSlash: true, assetPrefix: "/p" } : {}),
  ...(hosts.length ? { allowedDevOrigins: hosts } : {}),
};

export default nextConfig;
