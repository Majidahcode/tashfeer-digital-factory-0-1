"""
The layered (2.5D) factory trial's assets, from the owner's images (design/factory-layers/originals, unchanged):
    python3 scripts/factory-layers-assets.py

Writes public/factory-layers/*.webp (the same pictures, re-encoded for the web: alpha kept, size capped) and
src/components/factory/layered/assets.json (each picture's size, and where its parts are, in its own pixels).

"-empty" variants: the station with the drawn content inside its inner panel removed — filled by a smooth patch from
the panel's own edges. A stopgap for this trial only: it shows its seams up close, so the scene shows it only under the
project's content panel, which covers that area entirely. The real assets needed are listed in the review notes.
"""

import json
import os

import numpy as np
from PIL import Image
from scipy.ndimage import gaussian_filter1d

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "design", "factory-layers", "originals")
OUT = os.path.join(ROOT, "public", "factory-layers")
MANIFEST = os.path.join(ROOT, "src", "components", "factory", "layered", "assets.json")
MAX_SIDE = 2048  # the belt (2137 px) comes down to 2048; the stations (≤ 1354 px) stay at their size

# where things are, in each original's pixels (read from the pictures on a grid)
STATIONS = {
    # the inner panel's inside (the content area) and the base's foot (bottom centre, where it stands on the belt)
    "station-04": {"content": [452, 432, 1046, 752], "foot": [700, 1040]},
    "station-05": {"content": [428, 488, 940, 800], "foot": [632, 1150]},
}
# points on the belt's running surface (its middle line), from near (left) to far (right)
BELT = {"surface": [[300, 470], [650, 450], [1000, 415], [1250, 372], [1500, 333]]}


def coons(img, x0, y0, x1, y1, band=6, sigma=18):
    out = img.astype(np.float32).copy()
    H, W = y1 - y0, x1 - x0
    T = gaussian_filter1d(img[y0 - band:y0, x0:x1].astype(np.float32).mean(0), sigma, axis=0)
    B = gaussian_filter1d(img[y1:y1 + band, x0:x1].astype(np.float32).mean(0), sigma, axis=0)
    L = gaussian_filter1d(img[y0:y1, x0 - band:x0].astype(np.float32).mean(1), sigma, axis=0)
    R = gaussian_filter1d(img[y0:y1, x1:x1 + band].astype(np.float32).mean(1), sigma, axis=0)
    u = np.linspace(0, 1, W)[None, :, None]
    v = np.linspace(0, 1, H)[:, None, None]
    patch = (1 - v) * T[None] + v * B[None] + (1 - u) * L[:, None] + u * R[:, None] - (
        (1 - u) * (1 - v) * T[0] + u * (1 - v) * T[-1] + (1 - u) * v * B[0] + u * v * B[-1]
    )
    out[y0:y1, x0:x1] = patch
    return np.clip(out, 0, 255).astype(np.uint8)


def save(im, name):
    w, h = im.size
    k = min(1.0, MAX_SIDE / max(w, h))
    if k < 1:
        im = im.resize((round(w * k), round(h * k)), Image.LANCZOS)
    path = os.path.join(OUT, name + ".webp")
    im.save(path, "WEBP", quality=90, method=6)
    return {"src": f"/factory-layers/{name}.webp", "w": im.width, "h": im.height, "scale": k, "bytes": os.path.getsize(path)}


def main():
    os.makedirs(OUT, exist_ok=True)
    manifest = {"note": "generated by scripts/factory-layers-assets.py — coordinates are in the original pictures' pixels"}
    belt = Image.open(os.path.join(SRC, "belt.png")).convert("RGBA")
    manifest["belt"] = {**save(belt, "belt"), "original": list(belt.size), **BELT}
    for name, info in STATIONS.items():
        im = Image.open(os.path.join(SRC, name + ".png")).convert("RGBA")
        empty = Image.fromarray(coons(np.asarray(im), *info["content"]))
        manifest[name] = {
            **save(im, name),
            "empty": save(empty, name + "-empty"),
            "original": list(im.size),
            **info,
        }
    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
    total = sum(v["bytes"] + v.get("empty", {}).get("bytes", 0) for k, v in manifest.items() if isinstance(v, dict))
    print(json.dumps({k: (v["w"], v["h"], v["bytes"]) for k, v in manifest.items() if isinstance(v, dict)}), f"total {total/1024:.0f} KB")


main()
