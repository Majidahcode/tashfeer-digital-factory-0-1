#!/usr/bin/env node
/**
 * Copies / extracts approved artwork from the reference package into public/assets
 * and writes src/generated/asset-manifest.json (dimensions, format, alpha, sha256).
 *
 *   node scripts/sync-assets.mjs           # sync + write manifest
 *   node scripts/sync-assets.mjs --check   # verify the committed manifest matches the sources (CI)
 *
 * Never writes inside the package folder.
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import sharp from "sharp";
import {
  AGENTS_DIR,
  AGENT_SOURCES,
  EMBEDDED_ASSETS,
  FILE_ASSETS,
  MANIFEST_PATH,
  OUTPUT_DIR,
  PACKAGE_ROOT,
  PROTOTYPE_HTML,
  PUBLIC_PREFIX,
} from "./assets.config.mjs";

const CHECK = process.argv.includes("--check");
const root = process.cwd();
const errors = [];

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const extFor = (format) => (format === "jpeg" ? "jpg" : format);

async function describe(buf, label, expect) {
  const meta = await sharp(buf).metadata();
  const info = { format: meta.format, width: meta.width, height: meta.height, hasAlpha: Boolean(meta.hasAlpha) };
  if (expect?.format && info.format !== expect.format) errors.push(`${label}: expected ${expect.format}, got ${info.format}`);
  if (expect?.alpha && !info.hasAlpha) errors.push(`${label}: expected an alpha channel`);
  return info;
}

async function emit(relTo, buf) {
  if (CHECK) return;
  const out = path.join(root, OUTPUT_DIR, relTo);
  await mkdir(path.dirname(out), { recursive: true });
  if (existsSync(out)) {
    const current = await readFile(out);
    if (sha256(current) === sha256(buf)) return;
  }
  await writeFile(out, buf);
}

function extractDataUri(html, after, label) {
  const anchor = html.indexOf(after);
  if (anchor < 0) {
    errors.push(`${label}: context "${after}" not found in prototype`);
    return null;
  }
  const start = html.indexOf("data:", anchor);
  const m = /^data:([a-z]+\/[a-z0-9.+-]+);base64,([A-Za-z0-9+/=]+)/.exec(html.slice(start, start + 3_000_000));
  if (!m) {
    errors.push(`${label}: no base64 data URI after "${after}"`);
    return null;
  }
  return Buffer.from(m[2], "base64");
}

async function main() {
  const manifest = {
    note: "Generated by scripts/sync-assets.mjs from the read-only reference package. Do not edit by hand.",
    packageRoot: PACKAGE_ROOT,
    assets: {},
    agents: {},
  };

  for (const a of FILE_ASSETS) {
    const src = path.join(root, a.from);
    if (!existsSync(src)) {
      errors.push(`${a.id}: missing source ${a.from}`);
      continue;
    }
    const buf = await readFile(src);
    const info = await describe(buf, a.id, a.expect);
    await emit(a.to, buf);
    manifest.assets[a.id] = { src: `${PUBLIC_PREFIX}/${a.to}`, ...info, sha256: sha256(buf), source: a.from };
  }

  const html = await readFile(path.join(root, PROTOTYPE_HTML), "utf8");
  for (const a of EMBEDDED_ASSETS) {
    const buf = extractDataUri(html, a.after, a.id);
    if (!buf) continue;
    const info = await describe(buf, a.id, a.expect);
    await emit(a.to, buf);
    manifest.assets[a.id] = {
      src: `${PUBLIC_PREFIX}/${a.to}`,
      ...info,
      sha256: sha256(buf),
      source: `${PROTOTYPE_HTML} (embedded after ${a.after})`,
    };
  }

  for (const [role, file] of Object.entries(AGENT_SOURCES)) {
    if (!file) {
      manifest.agents[role] = { status: "missing" };
      continue;
    }
    const src = path.join(root, AGENTS_DIR, file);
    if (!existsSync(src)) {
      errors.push(`agent ${role}: mapped file not found: ${file}`);
      manifest.agents[role] = { status: "missing" };
      continue;
    }
    const buf = await readFile(src);
    const info = await describe(buf, `agent ${role}`, { alpha: true });
    const to = `agents/${role}.${extFor(info.format)}`;
    await emit(to, buf);
    manifest.agents[role] = {
      status: "available",
      approval: "pending DEC-03",
      src: `${PUBLIC_PREFIX}/${to}`,
      ...info,
      sha256: sha256(buf),
      source: `${AGENTS_DIR}/${file}`,
    };
  }

  const serialized = `${JSON.stringify(manifest, null, 2)}\n`;
  const manifestFile = path.join(root, MANIFEST_PATH);

  if (CHECK) {
    const committed = existsSync(manifestFile) ? await readFile(manifestFile, "utf8") : "";
    if (committed !== serialized) errors.push(`${MANIFEST_PATH} is out of date — run: npm run assets:sync`);
  } else {
    await mkdir(path.dirname(manifestFile), { recursive: true });
    await writeFile(manifestFile, serialized);
  }

  if (errors.length) {
    console.error(`asset sync failed:\n  - ${errors.join("\n  - ")}`);
    process.exit(1);
  }
  const missing = Object.entries(manifest.agents).filter(([, v]) => v.status === "missing").map(([k]) => k);
  console.log(
    `${CHECK ? "checked" : "synced"} ${Object.keys(manifest.assets).length} assets + ${
      Object.keys(manifest.agents).length - missing.length
    }/12 agent images${missing.length ? ` (missing: ${missing.join(", ")})` : ""}`,
  );
}

await main();
